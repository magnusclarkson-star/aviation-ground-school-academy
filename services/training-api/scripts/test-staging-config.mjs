import assert from "node:assert/strict";
import {readFile,stat} from "node:fs/promises";
import path from "node:path";
import {fileURLToPath} from "node:url";
const here=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
const spec=JSON.parse(await readFile(process.argv[2]||"/tmp/agsa-staging-compose.json","utf8"));
const api=spec.services?.api,gateway=spec.services?.gateway;
assert.ok(api&&gateway,"staging needs a separate API and HTTPS gateway");
assert.equal(api.read_only,true,"API container root file system should be read-only");
assert.ok(api.security_opt?.includes("no-new-privileges:true"));
assert.ok(api.cap_drop?.includes("ALL"));
assert.equal(api.ports?.length||0,0,"never publish API port directly to host");
assert.ok(api.expose?.some(x=>String(x)==="3100"),"API may expose only the internal port");
assert.equal(api.environment.NODE_ENV,"production");
assert.equal(api.environment.PGSSL_MODE,"verify-full");
assert.equal(api.environment.AGSA_ALLOW_INSECURE_LOCAL,"0");
assert.equal(api.environment.AGSA_PRIVATE_PROXY_CONFIRMED,"1");
assert.ok(String(api.environment.AGSA_PUBLIC_ORIGIN).startsWith("https://"));
assert.ok(gateway.ports?.some(x=>String(x.published)==="443"));
assert.ok(gateway.ports?.some(x=>String(x.published)==="80"));
assert.ok(gateway.networks&&api.networks,"gateway and API need a shared private bridge");
assert.ok(Object.keys(gateway.networks).some(n=>Object.hasOwn(api.networks,n)),"network mismatch");
const docker=await readFile(path.join(here,"Dockerfile"),"utf8");
assert.match(docker,/npm ci --omit=dev/);
assert.match(docker,/^USER node$/m);
assert.doesNotMatch(docker,/COPY\s+\.\s+/,"do not copy all repository secrets into image");
await stat(path.join(here,"package-lock.json"));
console.log("Staging manifest passed: HTTPS gateway only, no API host port, non-root read-only application, locked dependencies, verified PostgreSQL TLS.");
