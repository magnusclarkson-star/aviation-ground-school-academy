import assert from "node:assert/strict";
import path from "node:path";
import {pathToFileURL} from "node:url";
import {chromium} from "playwright";
const file=pathToFileURL(path.resolve("cockpit-v3.html")).href+"?mode=mission";
const browser=await chromium.launch({headless:true,args:["--no-sandbox"]});
const errors=[];
try{
 const desktop=await browser.newPage({viewport:{width:1280,height:900}});
 desktop.on("pageerror",e=>errors.push("desktop: "+e.message));
 await desktop.goto(file,{waitUntil:"load"});
 await desktop.locator("#missionPanel").waitFor({state:"visible"});
 assert.equal(await desktop.locator("#missionMode").getAttribute("aria-pressed"),"true");
 assert.equal(await desktop.locator("#digitalSection").isVisible(),true);
 assert.equal(await desktop.locator("#pfdSvg").isVisible(),true);
 assert.equal(await desktop.locator("#digitalControlDock #control-throttle").count(),1);
 assert.equal(await desktop.locator("#digitalControlDock #control-yoke").count(),1);
 assert.equal(await desktop.locator("#digitalControlDock #control-flaps").count(),1);
 assert.match(await desktop.locator("#missionPhase").textContent(),/Takeoff roll/);
 assert.equal(await desktop.locator("#missionIAS").textContent(),"0 kt");
 await desktop.locator("#throttle").fill("90");
 await desktop.waitForTimeout(1050);
 assert.ok(Number((await desktop.locator("#missionIAS").textContent()).replace(" kt",""))>0,"runway roll should build speed from zero");
 await desktop.locator(".mission-jump summary").click();
 await desktop.locator('[data-mission-stage="approach"]').click();
 assert.match(await desktop.locator("#missionPhase").textContent(),/Stabilized approach/);
 assert.equal(await desktop.locator("#missionHeight").textContent(),"230 ft AGL");
 assert.equal(await desktop.locator("#missionGoAround").isVisible(),true);
 await desktop.locator("#flaps20").click();
 assert.equal(await desktop.locator("#missionFlaps").textContent(),"20°");
 await desktop.locator("#missionGoAround").click();
 assert.match(await desktop.locator("#missionPhase").textContent(),/Initial climb/);
 assert.equal(await desktop.locator("#outThrottle").textContent(),"86%");
 assert.equal(await desktop.locator("#missionFlaps").textContent(),"10°");
 await desktop.locator(".mission-jump summary").click();
 await desktop.locator('[data-mission-stage="landing"]').click();
 assert.match(await desktop.locator("#missionPhase").textContent(),/Landing and roundout/);
 await desktop.locator("#missionRestart").click();
 assert.match(await desktop.locator("#missionPhase").textContent(),/Takeoff roll/);
 assert.equal(await desktop.locator("#outThrottle").textContent(),"0%");
 await desktop.locator("#digitalMode").click();
 assert.equal(await desktop.locator("#missionPanel").isVisible(),false);
 assert.equal(await desktop.locator("#digitalSection").isVisible(),true);
 await desktop.locator("#missionMode").click();
 assert.match(await desktop.locator("#missionPhase").textContent(),/Takeoff roll/);
 await desktop.close();

 const phone=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 phone.on("pageerror",e=>errors.push("phone: "+e.message));
 await phone.goto(file,{waitUntil:"load"});
 await phone.locator("#missionPanel").waitFor({state:"visible"});
 assert.equal(await phone.locator("#digitalControlDock #control-yoke").count(),1);
 assert.equal(await phone.locator("#digitalControlDock #control-flaps").count(),1);
 await phone.locator("#flaps10").tap();
 assert.equal(await phone.locator("#missionFlaps").textContent(),"10°");
 await phone.locator("#throttle").fill("75");
 await phone.locator("#grip").scrollIntoViewIfNeeded();
 const rect=await phone.locator(".digital-screen-column").boundingBox();
 assert.ok(rect&&rect.y>-8&&rect.y<420,"live PFD stays visible on phone during mission controls");
 await phone.locator(".mission-jump summary").tap();
 await phone.locator('[data-mission-stage="landing"]').tap();
 assert.equal(await phone.locator("#digitalControlDock #control-flaps").count(),1);
 assert.match(await phone.locator("#missionPhase").textContent(),/Landing and roundout/);
 await phone.close();
 assert.deepEqual(errors,[],"No JS page exceptions");
 console.log("Guided Flight browser passed: direct launch, runway acceleration, stage reposition, flap input, go-around, reset, mode switch, Android touch controls and sticky PFD.");
}finally{await browser.close()}
