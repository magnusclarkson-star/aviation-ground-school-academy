import assert from "node:assert/strict";
import path from "node:path";
import {pathToFileURL} from "node:url";
import {chromium} from "playwright";

const url=pathToFileURL(path.resolve("cockpit-v3.html")).href+"?mode=skills";
const browser=await chromium.launch({headless:true,args:["--no-sandbox"]});
const errors=[];
try{
 const desktop=await browser.newPage({viewport:{width:1280,height:900},acceptDownloads:true});
 desktop.on("pageerror",e=>errors.push("desktop: "+e.message));
 await desktop.addInitScript(()=>{
  Object.defineProperty(window,"speechSynthesis",{configurable:true,value:{
   cancel:()=>{window.__coachCancelled=(window.__coachCancelled||0)+1;},
   speak:utterance=>{window.__coachSpoken=utterance.text;utterance.onstart?.();}
  }});
  window.SpeechSynthesisUtterance=class{constructor(text){this.text=text}};
 });
 await desktop.goto(url,{waitUntil:"load"});
 await desktop.locator("#skillsPanel").waitFor({state:"visible"});
 assert.equal(await desktop.locator("#skillsMode").getAttribute("aria-pressed"),"true");
 assert.equal(await desktop.locator("#skillsMiniStatus").isVisible(),true);
 assert.equal(await desktop.locator("#pfdSvg").isVisible(),true);
 assert.equal(await desktop.locator("#digitalControlDock #control-yoke").count(),1);
 assert.equal(await desktop.locator("#digitalControlDock #control-rudder").count(),1);
 assert.equal(await desktop.locator("#digitalControlDock #control-flaps").count(),1);
 assert.equal(await desktop.locator("#skillsExport").isDisabled(),true);
 assert.equal(await desktop.locator("#mapTab").isDisabled(),true);
 await desktop.locator("#skillsSelect").selectOption("climb");
 assert.equal(await desktop.locator("#digitalControlDock #control-throttle").count(),1);
 assert.equal(await desktop.locator("#digitalControlDock #control-rudder").count(),0,"climb focus hides unrelated rudder");
 assert.match(await desktop.locator("#skillsTarget").textContent(),/climb 300/);
 await desktop.locator("#skillsSelect").selectOption("flap");
 assert.equal(await desktop.locator("#digitalControlDock #control-flaps").count(),1);
 assert.equal(await desktop.locator("#digitalControlDock #control-throttle").count(),1);
 await desktop.locator("#skillsStart").click();
 assert.equal(await desktop.locator("#skillsSelect").isDisabled(),true);
 await desktop.locator("#flaps20").click();
 assert.equal(await desktop.locator("#outFlaps").textContent(),"20°");
 await desktop.waitForTimeout(12400);
 await desktop.locator("#skillsStage").waitFor({state:"visible"});
 assert.equal(await desktop.locator("#skillsStage").textContent(),"TARGET MET");
 assert.equal(await desktop.locator("#skillsStart").isDisabled(),false);
 assert.equal(await desktop.locator("#skillsExport").isDisabled(),false);
 assert.match(await desktop.locator("#skillsOutcome").textContent(),/PRACTICE TARGET MET/);
 assert.match(await desktop.locator("#coachHeadline").textContent(),/fictional practice target/i);
 assert.ok((await desktop.locator("#coachCriteria .coach-criterion").count())>=4,"criteria breakdown available");
 assert.match(await desktop.locator("#coachNextSteps").textContent(),/Repeat/);
 assert.match(await desktop.locator("#coachLessonLink").getAttribute("href"),/ai-instructor\.html\?lesson=flaps$/);
 assert.match(await desktop.locator("#coachLessonLink").textContent(),/Flaps, lift and drag/);
 assert.equal(await desktop.locator("#coachSpeak").isEnabled(),true);
 assert.equal(await desktop.evaluate(()=>window.__coachSpoken),undefined,"coaching is never narrated automatically");
 await desktop.locator("#coachSpeak").click();
 assert.match(await desktop.evaluate(()=>window.__coachSpoken),/Academy simulated practice review/i);
 assert.match(await desktop.evaluate(()=>window.__coachSpoken),/not a human instructor assessment or licence credit/i);
 assert.match(await desktop.locator("#coachVoiceStatus").textContent(),/synthetic browser speech/i);
 await desktop.locator("#coachStop").click();
 assert.match(await desktop.locator("#coachVoiceStatus").textContent(),/stopped/i);
 assert.ok(await desktop.evaluate(()=>window.__coachCancelled>0),"stop sends cancel to voice engine");
 const downloadPromise=desktop.waitForEvent("download");
 await desktop.locator("#skillsExport").click();
 const download=await downloadPromise;
 assert.match(download.suggestedFilename(),/academy-unofficial-flap-practice\.json/);
 const filepath=await download.path();
 const fs=await import("node:fs/promises");
 const report=JSON.parse(await fs.readFile(filepath,"utf8"));
 assert.equal(report.schema,"agsa.practice-observation.v1");
 assert.equal(report.task.id,"flap");
 assert.equal(report.observation.outcome,"PRACTICE_TARGET_MET");
 assert.match(report.disclaimer,/NOT A CERTIFICATE/);
 assert.equal(report.automatedPracticeFeedback.criterionScores.length,4);
 assert.match(report.automatedPracticeFeedback.label,/Automated practice coach/);
 assert.ok(!("learner" in report)&&!("studentId" in report));
 await desktop.locator("#skillsSelect").selectOption("turn");
 assert.equal(await desktop.locator("#digitalControlDock #control-rudder").count(),1);
 await desktop.locator("#skillsStart").click();
 await desktop.waitForTimeout(550);
 await desktop.locator("#skillsEnd").click();
 assert.equal(await desktop.locator("#skillsStage").textContent(),"REVIEW");
 assert.match(await desktop.locator("#skillsOutcome").textContent(),/INCOMPLETE/);
 assert.match(await desktop.locator("#coachLessonLink").getAttribute("href"),/lesson=controls$/);
 await desktop.locator("#digitalMode").click();
 assert.equal(await desktop.locator("#skillsPanel").isVisible(),false);
 assert.equal(await desktop.locator("#mapTab").isEnabled(),true,"normal digital cockpit is restored");
 await desktop.locator("#skillsMode").click();
 assert.equal(await desktop.locator("#skillsPanel").isVisible(),true);
 await desktop.close();

 const phone=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 phone.on("pageerror",e=>errors.push("phone: "+e.message));
 await phone.goto(url,{waitUntil:"load"});
 await phone.locator("#skillsPanel").waitFor({state:"visible"});
 await phone.locator("#skillsSelect").selectOption("turn");
 assert.equal(await phone.locator("#digitalControlDock #control-rudder").count(),1);
 await phone.locator("#controlTypeStick").tap();
 assert.equal(await phone.locator("#gripTypeLabel").textContent(),"STICK");
 await phone.locator("#skillsStart").tap();
 assert.equal(await phone.locator("#skillsStage").textContent(),"OBSERVING");
 await phone.locator("#grip").scrollIntoViewIfNeeded();
 const stickypfd=await phone.locator(".digital-screen-column").boundingBox();
 assert.ok(stickypfd&&stickypfd.y>=-8&&stickypfd.y<420,"live PFD remains visible while learner works controls");
 assert.equal(await phone.locator("#skillsMiniStatus").isVisible(),true);
 await phone.locator("#skillsEnd").tap();
 assert.equal(await phone.locator("#skillsExport").isDisabled(),false);
 assert.equal(await phone.locator("#coachSpeak").count(),1,"touchscreen has optional spoken review");
 await phone.locator("#skillsRetry").tap();
 assert.equal(await phone.locator("#skillsStage").textContent(),"READY");
 await phone.close();
 assert.deepEqual(errors,[],"No JS exceptions");
 console.log("Skills practice browser passed: PFD, focused controls, automatic 12-second observation, exportable unsigned report, incomplete retry and phone touch layout.");
}finally{await browser.close()}
