import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
const read=async name=>readFile(new URL("../"+name,import.meta.url),"utf8");
const html=await read("academy-certificate-gallery.html");
const css=await read("academy-certificate-gallery.css");
const js=await read("academy-certificate-gallery.js");
const course=await read("academy-coursebook.html");
const home=await read("index.html");
assert.equal((html.match(/class="certificate-card"/g)||[]).length,1,
 "Exactly one permanent Academy standard certificate should be shown");
assert.match(html,/class="certificate academy-standard"/);
assert.match(html,/id="academyStandard"/);
assert.match(html,/SAMPLE · NOT ISSUED/);
assert.match(html,/DEMO-NOT-VALID/);
assert.match(html,/Permanent A4 landscape design/);
assert.match(html,/data-print="formal"/);
assert.match(html,/no certificate artwork upload|No certificate artwork upload/i);
assert.doesNotMatch(html,/<input[^>]+type="file"/i,"A certificate sample must not depend on uploading a file");
assert.doesNotMatch(html,/Choose the right certificate|Show original Academy seal/);
assert.match(css,/\.certificate\.academy-standard/);
assert.doesNotMatch(css,/\.gallery \.certificate\{display:none!important\}/);
assert.match(css,/body\[data-print-style=formal\]/);
assert.match(js,/window\.print\(\)/);
assert.doesNotMatch(js,/fetch\(|XMLHttpRequest|indexedDB|crypto\.subtle|localStorage|sessionStorage|sendBeacon|createObjectURL|type="file"/,
 "Permanent specimen must never need browser file storage, crypto verification, or upload");
assert.ok(home.includes('href="academy-certificate-gallery.html"'));
assert.ok(course.includes('href="academy-certificate-gallery.html"'));
assert.match(css,/@media print/);
assert.match(html,/no personal signatures or real student records/i);
console.log("Academy standard certificate: one visible printable specimen, no upload, watermark and private-data separation passed.");
