import assert from "node:assert/strict";
import {createRequire} from "node:module";
const require=createRequire(import.meta.url);
const M=require("../cockpit-v3-model.js");
const simulate=(seconds, input, start)=>{
 const s=start||M.makeState();const dt=.025;
 for(let i=0;i<seconds/dt;i++)M.step(s,input,dt);
 return s;
};
assert.equal(M.makeInput().throttle,55);
let up=M.makeInput();up.yokeY=-.8;up.throttle=85;
let climb=simulate(8,up);
assert.ok(climb.pitch>8,"back yoke should increase pitch");
assert.ok(climb.verticalSpeed>0,"nose up with power should climb");
assert.ok(climb.altitude>3500,"climb should increase altitude");
let down=M.makeInput();down.yokeY=.8;down.throttle=25;
let descent=simulate(8,down);
assert.ok(descent.pitch< -8,"forward yoke should reduce pitch");
assert.ok(descent.verticalSpeed<0,"nose down low power should descend");
assert.ok(descent.altitude<3500,"descent should reduce altitude");
let right=M.makeInput();right.yokeX=.8;
let r=simulate(12,right);
assert.ok(r.roll>20,"right yoke commands right bank");
assert.ok(r.heading>270,"right bank should increase heading");
let left=M.makeInput();left.yokeX=-.8;
let l=simulate(12,left);
assert.ok(l.roll< -20,"left yoke commands left bank");
assert.ok(l.heading<270,"left bank should decrease heading");
let throttleHigh=M.makeInput();throttleHigh.throttle=90;
let throttleLow=M.makeInput();throttleLow.throttle=30;
let high=simulate(15,throttleHigh);
let low=simulate(15,throttleLow);
assert.ok(high.speed>low.speed+20,"power should increase airspeed in level flight");
let rudder=M.makeInput();rudder.rudder=1;
let yaw=simulate(8,rudder);
assert.ok(yaw.turnRate>0,"rudder should alter yaw/turn indication");
assert.ok(yaw.slip>.5,"rudder should move the slip indicator");
assert.ok(yaw.distance>0,"aircraft travels forward in teaching model");
let flaps=M.makeInput();flaps.flaps=30;flaps.throttle=60;
let clean=M.makeInput();clean.flaps=0;clean.throttle=60;
assert.ok(simulate(12,flaps).speed<simulate(12,clean).speed,"flap setting should change speed");
let extreme=M.makeInput();extreme.yokeX=99;extreme.yokeY=-99;extreme.throttle=999;
let limited=simulate(20,extreme);
assert.ok(Math.abs(limited.roll)<=45&&Math.abs(limited.pitch)<=25&&limited.speed<=180);

const cleanEffect=M.flapEffects(0);
const firstEffect=M.flapEffects(10);
const fullEffect=M.flapEffects(30);
assert.equal(cleanEffect.liftIndex,1);
assert.equal(cleanEffect.dragIndex,1);
assert.ok(firstEffect.liftIndex>cleanEffect.liftIndex);
assert.ok(firstEffect.dragIndex>cleanEffect.dragIndex);
assert.ok(fullEffect.liftIndex>firstEffect.liftIndex);
assert.ok(fullEffect.dragIndex>firstEffect.dragIndex);
assert.ok(fullEffect.dragIndex-firstEffect.dragIndex>fullEffect.liftIndex-firstEffect.liftIndex,"large deflections add disproportionate drag");
const hold=M.makeInput();hold.throttle=55;hold.flaps=0;
const cleanTrial=simulate(15,hold);
hold.flaps=10;const partialTrial=simulate(15,hold);
hold.flaps=30;const fullTrial=simulate(15,hold);
assert.ok(partialTrial.liftIndex>1);
assert.ok(partialTrial.verticalSpeed>cleanTrial.verticalSpeed+15,"partial flaps produce upward tendency in teaching model");
assert.ok(fullTrial.dragIndex>2,"full flaps produce substantial relative drag");
assert.ok(fullTrial.speed<cleanTrial.speed-10,"large flap deflection slows aircraft at same power and pitch");
assert.ok(fullTrial.verticalSpeed<cleanTrial.verticalSpeed-125,"large flap deflection increases descent tendency");
assert.ok(fullTrial.altitude<cleanTrial.altitude,"larger flap drag affects altitude over time");
const retraction=M.makeInput();retraction.throttle=55;retraction.flaps=0;
const beforeRetraction=fullTrial.speed;
simulate(12,retraction,fullTrial);
assert.ok(fullTrial.speed>beforeRetraction,"retraction reduces drag and allows speed recovery");
assert.ok(fullTrial.flaps<.5&&fullTrial.dragIndex<1.02,"indicated flaps and drag index approach clean reference");
console.log("V3 flap aerodynamics passed: normalized lift/drag curves, partial-lift tendency, full-flap drag and airspeed/descent effects, retraction.");
console.log("V3 model passed: pitch, bank, heading, VSI, altitude, throttle, flaps, rudder, distance and bounds.");
