import assert from 'node:assert/strict';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import {chromium} from 'playwright';

const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const file=pathToFileURL(path.resolve('cockpit-v3.html')).href;
const errors=[];
try {
 const page=await browser.newPage({viewport:{width:1280,height:900}});
 page.on('pageerror',error=>errors.push('desktop: '+error.message));
 await page.goto(file,{waitUntil:'load'});
 await page.locator('#dial-asi svg').waitFor();
 assert.equal(await page.locator('.dial-tile svg').count(),6,'six round analogue gauges');
 assert.equal(await page.locator('#analogSection').isVisible(),true);
 await page.locator('#digitalMode').click();
 assert.equal(await page.locator('#digitalSection').isVisible(),true);
 assert.equal(await page.locator('#pfdSvg').isVisible(),true);
 await page.locator('#mapTab').click();
 assert.equal(await page.locator('#mapView').isVisible(),true);
 await page.locator('#engineTab').click();
 assert.equal(await page.locator('#engineView').isVisible(),true);
 await page.locator('#pfdTab').click();
 assert.equal(await page.locator('#pfdView').isVisible(),true);
 await page.locator('#analogMode').click();
 await page.locator('#presetClimb').click();
 await page.waitForTimeout(950);
 const pitch=Number((await page.locator('#read-att').textContent()).split('°')[0]);
 assert.ok(pitch>0.8,'climb demonstration should increase indicated pitch');
 await page.locator('#presetRight').click();
 await page.waitForTimeout(950);
 const roll=Number((await page.locator('#read-att').textContent()).split(' · ')[1].split('°')[0]);
 assert.ok(roll>1,'right turn demo should produce right bank');
 await page.locator('#resetBtn').click();
 assert.match(await page.locator('#read-att').textContent(),/^0.0° PITCH/);
 await page.locator('#throttle').fill('95');
 assert.equal(await page.locator('#outThrottle').textContent(),'95%');
 await page.locator('#flaps20').click();
 assert.equal(await page.locator('#outFlaps').textContent(),'20°');
 await page.locator('#runSelfTest').click();
 assert.match(await page.locator('#selfTestResult').textContent(),/PASS/);
 await page.close();

 const phone=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 phone.on('pageerror',error=>errors.push('Android-like: '+error.message));
 await phone.goto(file,{waitUntil:'load'});
 await phone.locator('#dial-asi svg').waitFor();
 await phone.locator('#digitalMode').tap();
 assert.equal(await phone.locator('#digitalSection').isVisible(),true);
 await phone.locator('#mapTab').tap();
 assert.equal(await phone.locator('#mapView').isVisible(),true);
 await phone.locator('#engineTab').tap();
 assert.equal(await phone.locator('#engineView').isVisible(),true);
 await phone.locator('#analogMode').tap();
 await phone.locator('#flaps10').tap();
 assert.equal(await phone.locator('#outFlaps').textContent(),'10°');
 await phone.locator('#resetBtn').tap();
 assert.equal(await phone.locator('#outFlaps').textContent(),'0°');
 await phone.close();
 assert.deepEqual(errors,[],'No runtime page errors');
 console.log('Browser smoke passed: desktop analogue, PFD, map, engine, presets, reset, throttle, flaps, self-test; Android-sized touchscreen navigation.');
} finally {await browser.close();}
