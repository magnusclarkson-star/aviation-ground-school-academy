import assert from "node:assert/strict";
import {createRequire} from "node:module";
const require=createRequire(import.meta.url);
const P=require("../ai-instructor-progress.js");
const L=require("../ai-instructor-lessons.js");
const ids=L.lessons.map(x=>x.id);
const store=new Map();
const storage={getItem:k=>store.get(k)||null,setItem:(k,v)=>store.set(k,v)};
assert.deepEqual(P.load(storage,ids),[]);
let h=P.record([],"flaps",false,ids,100);
let o=P.overview(h,L.lessons);
assert.equal(o.total,1);
assert.equal(o.correct,0);
assert.equal(o.recommended,"flaps");
h=P.record(h,"flaps",true,ids,200);
o=P.overview(h,L.lessons);
assert.equal(o.total,2);
assert.equal(o.percent,50);
assert.equal(o.recommended,"forces"); // new topics rank ahead of a partially learned topic once latest correct
assert.equal(P.save(storage,h,ids),true);
assert.deepEqual(P.load(storage,ids),h);
assert.throws(()=>P.record(h,"unknown",true,ids),/Invalid/);
assert.throws(()=>P.record(h,"flaps","yes",ids),/Invalid/);
store.set(P.KEY,"not-json");
assert.deepEqual(P.load(storage,ids),[]);
assert.equal(P.save({setItem(){throw Error("restricted")}},h,ids),false);
h=Array.from({length:130},(_,i)=>({id:"forces",correct:i%2===0,at:i}));
assert.equal(P.overview(h,L.lessons).total,100,"bounded device-only history");
console.log("AI Instructor local progress and recommendation tests passed.");
